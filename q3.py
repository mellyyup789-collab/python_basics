student_age = 20
minimum_age = 18

print("Equal to (==):", student_age == minimum_age)
print("Not equal to (!=):", student_age != minimum_age)
print("Greater than (>):", student_age > minimum_age)
print("Less than (<):", student_age < minimum_age)
print("Greater than or equal to (>=):", student_age >= minimum_age)
print("Less than or equal to (<=):", student_age <= minimum_age)